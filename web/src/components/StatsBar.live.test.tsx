import { act, render, screen } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { StatsBar } from "./StatsBar.js";
import type { ChatState, TimelineItem } from "pi-agent-server/client";
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks(); });
it("shows live estimate by default, expires at 2s, and prefers fresh real delta over concurrent tools", () => {
  vi.useFakeTimers();
  let clock = 100; vi.spyOn(performance, "now").mockImplementation(() => clock);
  const progress: ChatState["modelOutput"] = { ordinal: 1, phase: "delta", tokensPerSecondEstimate: 100, includesThinking: true, receivedAt: 100 };
  const tools: TimelineItem[] = [{ kind: "tool", id: "t", call: { toolCallId: "t", toolName: "bash", args: {}, partialResult: null, result: null, isError: false, done: false } }];
  const view = render(<StatsBar stats={null} connected pending timeline={[]} modelOutput={progress} />);
  expect(screen.getByTestId("stat-live-speed")).toHaveTextContent("~100 tok/s");
  expect(screen.getByTestId("stats-bar")).not.toHaveTextContent("估算");
  clock = 2101; act(() => vi.advanceTimersByTime(2001));
  expect(screen.getByTestId("stats-bar")).not.toHaveTextContent("tok/s");
  expect(screen.queryByTestId("stat-live-speed")).not.toBeInTheDocument();
  view.rerender(<StatsBar stats={null} connected pending timeline={tools} modelOutput={progress} />);
  expect(screen.getByTestId("stats-bar")).not.toHaveTextContent("工具执行中");
  view.rerender(<StatsBar stats={null} connected pending timeline={tools} modelOutput={{ ...progress, receivedAt: clock }} />);
  expect(screen.getByTestId("stat-live-speed")).toHaveTextContent("~100 tok/s");
  view.rerender(<StatsBar stats={null} connected={false} pending timeline={tools} modelOutput={progress} />);
  expect(screen.getByTestId("stats-bar")).not.toHaveTextContent("tok/s");
  expect(screen.queryByTestId("stat-live-speed")).not.toBeInTheDocument();
  view.rerender(<StatsBar stats={null} connected timeline={tools} modelOutput={progress} />);
  expect(screen.queryByTestId("stat-live")).not.toBeInTheDocument();
  view.unmount(); expect(vi.getTimerCount()).toBe(0);
});
it("does not invent zero for first delivery and does not put frequently changing numbers in aria-live", () => {
  render(<StatsBar stats={null} connected pending timeline={[]} modelOutput={{ ordinal: 1, phase: "delta", tokensPerSecondEstimate: null, includesThinking: false, receivedAt: performance.now() }} />);
  expect(screen.queryByTestId("stat-live-speed")).toBeNull();
  expect(screen.queryByRole("status")).toBeNull();
});
