import { test, expect } from '@playwright/test';
import { workspaceFixture } from './workspace.fixture';
import { appearance } from './focus-appearance';

test('single theme entry: keyboard, system changes, collapsed rail and mobile recovery', async ({ page }) => {
  // Playwright's fresh context isolates storage; preserve it across reloads here.
  const unexpected = await workspaceFixture(page, undefined, false);
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1536, height: 1024 });
  await page.goto('/');
  const trigger = page.getByTestId('theme-toggle');
  const app = page.getByTestId('app');
  const system = page.getByRole('menuitemradio', { name: '跟随系统', exact: true });
  const open = async () => {
    await trigger.click();
    await expect(page.getByRole('menuitemradio')).toHaveText([/浅色$/, /深色$/, /跟随系统$/]);
  };
  const choose = async (name: string) => {
    await open();
    await page.getByRole('menuitemradio', { name, exact: true }).click();
    await expect(trigger).toBeFocused();
  };
  await expect(trigger).toHaveCount(1);
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme });
    await expect(app).toHaveAttribute('data-theme', theme);
    await page.mouse.move(800, 0);
    await trigger.evaluate(el => (el as HTMLElement).blur());
    const resting = await appearance(trigger);
    await trigger.click();
    await expect(page.getByRole('menu')).toBeVisible();
    // Mouse selection closes the menu and Radix restores real DOM focus.
    await system.click();
    await page.mouse.move(800, 0);
    await expect(trigger).toBeFocused();
    expect(await appearance(trigger)).toEqual(resting);
    await page.screenshot({ path: `test-results/workspace/focus-${theme}-mouse-close.png` });
    await trigger.click();
    await page.mouse.move(800, 0);
    await expect(trigger).toHaveCSS('outline-style', 'none');
    await page.screenshot({ path: `test-results/workspace/focus-${theme}-click-menu.png` });
    await page.keyboard.press('Escape');
    await expect(trigger).toBeFocused();
    await expect(trigger).toHaveCSS('outline-style', 'none');
    await expect(trigger).toHaveCSS('box-shadow', 'none');
    await page.screenshot({ path: `test-results/workspace/focus-${theme}-escape.png` });
    await page.keyboard.press('Shift+Tab');
    await page.keyboard.press('Tab');
    await expect(trigger).toBeFocused();
    await expect(trigger).toHaveCSS('outline-style', 'none');
    expect(await appearance(trigger)).toEqual(resting);
    await page.screenshot({ path: `test-results/workspace/focus-${theme}-tab.png` });
    await page.keyboard.press('ArrowDown');
    const first = page.getByRole('menuitemradio', { name: '浅色', exact: true });
    await expect(first).toBeFocused();
    const focused = await appearance(first);
    await page.keyboard.press('ArrowDown');
    await expect(page.getByRole('menuitemradio', { name: '深色', exact: true })).toBeFocused();
    expect(await appearance(first)).toEqual(focused);
    await page.keyboard.press('ArrowUp');
    await expect(first).toBeFocused();
    await page.screenshot({ path: `test-results/workspace/focus-${theme}-keyboard-menu.png` });
    await first.hover();
    expect(await appearance(first)).not.toEqual(focused);
    await page.mouse.move(800, 0);
    await page.keyboard.press('Escape');
  }
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(page.locator('.theme-system')).toHaveCount(0);
  await expect(page.getByText('已跟随系统')).toHaveCount(0);
  const box = (await trigger.boundingBox())!;
  expect(box.y).toBeGreaterThan(900);
  await page.screenshot({ path: 'test-results/workspace/theme-single-entry.png' });
  await trigger.focus();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('menuitemradio', { name: '浅色', exact: true })).toBeFocused();
  await expect(system).toHaveAttribute('aria-checked', 'true');
  await page.screenshot({ path: 'test-results/workspace/theme-desktop-menu.png' });
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('menuitemradio', { name: '深色', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await expect(trigger).toBeFocused();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await open();
  await expect(page.getByRole('menuitemradio', { name: '深色', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.keyboard.press('Escape');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await choose('浅色');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.reload();
  await expect(app).toHaveAttribute('data-theme', 'light');
  await open();
  await expect(page.getByRole('menuitemradio', { name: '浅色', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.keyboard.press('Escape');
  await page.emulateMedia({ colorScheme: 'light' });
  await choose('跟随系统');
  await expect(app).toHaveAttribute('data-theme', 'light');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await page.getByTestId('toggle-sidebar').click();
  await choose('浅色');
  await open();
  await expect(page.getByRole('menuitemradio', { name: '浅色', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.screenshot({ path: 'test-results/workspace/theme-collapsed-menu.png' });
  await system.click();
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '打开工作区导航' }).click();
  await choose('浅色');
  await open();
  await page.screenshot({ path: 'test-results/workspace/theme-mobile-menu.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(page.getByTestId('sidebar')).toBeVisible();
  await choose('跟随系统');
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await open();
  await expect(system).toHaveAttribute('aria-checked', 'true');
  await page.screenshot({ path: 'test-results/workspace/theme-mobile-system.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByTestId('sidebar')).toBeHidden();
  // Reload restores system mode itself, not the last resolved dark palette.
  await page.reload();
  await expect(app).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: '打开工作区导航' }).click();
  await open();
  await expect(system).toHaveAttribute('aria-checked', 'true');
  await page.keyboard.press('Escape');
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(app).toHaveAttribute('data-theme', 'light');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(app).toHaveAttribute('data-theme', 'dark');
  expect(unexpected).toEqual([]);
});
